const LANG_SET = new Set<string>(LANGS);

export function isLang(value: string | null): value is Lang {
  return !!value && LANG_SET.has(value);
}

export function matchLang(input: string): Lang {
  const value = input.toLowerCase().replaceAll("_", "-");
  if (value.startsWith("zh")) {
    if (value.includes("hant") || value.endsWith("-tw") || value.endsWith("-hk") || value.endsWith("-mo")) return "zh-Hant";
    return "zh";
  }
  const base = value.split("-")[0] ?? "";
  if (base === "nb" || base === "nn") return "no";
  if (base === "iw") return "he";
  if (isLang(base)) return base;
  return "en";
}

export function languageChoices(browser: Lang): { id: Lang; label: string }[] {
  const rest = LANGS.filter((id) => id !== "en" && id !== browser).sort((a, b) =>
    LANGUAGE_LABELS[a].localeCompare(LANGUAGE_LABELS[b], "en"),
  );
  const ids: Lang[] = browser === "en" ? ["en", ...rest] : ["en", browser, ...rest];
  return ids.map((id) => ({ id, label: LANGUAGE_LABELS[id] }));
}

function applyDocumentLang(next: Lang) {
  document.documentElement.lang = next;
  document.documentElement.dir = RTL.has(next) ? "rtl" : "ltr";
}

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: StringKey) => string;
  country: (id: string, fallback: string) => string;
  languages: { id: Lang; label: string }[];
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [browserLang, setBrowserLang] = useState<Lang>("en");

  useEffect(() => {
    const detected = matchLang(navigator.language || "en");
    setBrowserLang(detected);
    const saved = localStorage.getItem("avatarlade-lang");
    const next = isLang(saved) ? saved : detected;
    setLangState(next);
    applyDocumentLang(next);
  }, []);

  const value = useMemo<I18nValue>(() => {
    return {
      lang,
      languages: languageChoices(browserLang),
      setLang: (next) => {
        if (!isLang(next)) return;
        localStorage.setItem("avatarlade-lang", next);
        applyDocumentLang(next);
        setLangState(next);
      },
      t: (key) => STRINGS[lang][key] || en[key],
      country: (id, fallback) => {
        try {
          const name = new Intl.DisplayNames([lang], { type: "region" }).of(id.toUpperCase());
          return name || fallback;
        } catch {
          return fallback;
        }
      },
    };
  }, [lang, browserLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n outside provider");
  return value;
}
